"""Resumable setup for catalog resorts: locate -> calibrate. Sleeps through Open-Meteo
hourly/daily limits instead of failing. Safe to rerun; skips finished work.

    python3 backfill.py                      # everything, sequentially (local)
    python3 backfill.py --group west --out o # CI: one region, results to o/{resorts,calibration}.json
    python3 backfill.py --merge DIR          # CI: merge region outputs from DIR/*/ into data/,
                                             #     add regional defaults, write CALIBRATION.md
"""
import glob, json, os, sys
import sources
from sources import write_json
sources.WAIT_ON_QUOTA = True
import calibrate, config, locate, update
from catalog import CATALOG

HERE = os.path.dirname(os.path.abspath(__file__))
RES_PATH = os.path.join(HERE, "data", "resorts.json")
CAL_PATH = os.path.join(HERE, "data", "calibration.json")


def load(p):
    return json.load(open(p)) if os.path.exists(p) else {}


def run(group=None, out=None):
    keys = [k for k, c in CATALOG.items() if not group or c[1] in update.GROUPS[group]]
    resorts = load(RES_PATH)
    missing = [k for k in keys if k not in resorts]
    if missing:  # locate.main([]) means "all missing", so only call it with real work
        locate.main(missing)
    resorts = load(RES_PATH)
    config.RESORTS.clear(); config.RESORTS.update(resorts)  # modules share this dict
    cal = load(CAL_PATH)
    todo = [k for k in keys if k in resorts and resorts[k].get("obs")
            and (k not in cal or cal[k].get("uncalibrated"))]
    try:
        if todo:
            calibrate.main(todo)
    finally:  # always hand back progress (located resorts, finished calibrations), even on a crash
        cal = load(CAL_PATH)
        if out:
            os.makedirs(out, exist_ok=True)
            json.dump({k: resorts[k] for k in keys if k in resorts}, open(os.path.join(out, "resorts.json"), "w"), indent=1)
            json.dump({k: cal[k] for k in keys if k in cal and not cal[k].get("uncalibrated")},
                      open(os.path.join(out, "calibration.json"), "w"), indent=1)
    print(f"backfill {group or 'all'}: located {sum(k in resorts for k in keys)}/{len(keys)}, "
          f"calibrated {sum(k in cal and not cal[k].get('uncalibrated') for k in keys)}")


def merge(d):
    resorts, cal = load(RES_PATH), load(CAL_PATH)
    for part in sorted(glob.glob(os.path.join(d, "*", ""))):
        resorts.update(load(os.path.join(part, "resorts.json")))
        cal.update(load(os.path.join(part, "calibration.json")))
    keep = ("name", "region", "tz", "base", "mid", "summit", "dem_ft", "obs", "models", "afd_office")
    resorts = {k: {f: v[f] for f in keep if f in v} for k, v in resorts.items() if k in CATALOG}
    write_json(RES_PATH, resorts, indent=1)
    config.RESORTS.clear(); config.RESORTS.update(resorts)
    cal = {k: v for k, v in cal.items() if k in resorts}
    for k, r in resorts.items():
        if k not in cal or cal[k].get("uncalibrated"):
            cal[k] = calibrate.regional_default(cal, r)
    write_json(CAL_PATH, cal, indent=1)
    write_report(resorts, cal)


def write_report(resorts, cal):
    """CALIBRATION.md: what's calibrated, against which gauge, and how well."""
    lines = ["# Calibration status", "",
             "Generated by `backfill.py`. Each US resort's model precipitation is bias-corrected against a",
             "nearby gauge using two winters (2024-26) of as-issued forecasts. Error = mean absolute error of",
             "72 h liquid precipitation for the blend, after correction. Resorts without a gauge (Canada) use",
             "the median factors of calibrated resorts in their region.", "",
             "| Resort | Region | Status | Gauge | Gauge elev | 72 h windows | Blend error (in liquid / 72 h) |",
             "|---|---|---|---|---|---|---|"]
    for k, c in CATALOG.items():
        r, cl = resorts.get(k), cal.get(k)
        if not r:
            lines.append(f"| {c[0]} | {c[1]} | not located yet | | | | |"); continue
        o = r.get("obs")
        if cl and not cl.get("uncalibrated"):
            st, err = "calibrated", f"{cl['blend_mae72'] / 25.4:.2f}"
        elif o:
            st, err = "pending (regional default for now)", ""
        else:
            st, err = "regional default (no gauge)", ""
        lines.append(f"| {r['name']} | {r['region']} | {st} | {o[2] if o else '–'} | "
                     f"{f'{o[3]:,} ft' if o else '–'} | {cl.get('n_windows', '') if cl else ''} | {err} |")
    open(os.path.join(HERE, "CALIBRATION.md"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    a = sys.argv[1:]
    if "--merge" in a:
        merge(a[a.index("--merge") + 1])
    else:
        run(a[a.index("--group") + 1] if "--group" in a else None, a[a.index("--out") + 1] if "--out" in a else None)
        if "--group" not in a:
            merge(os.path.join(HERE, "__nothing__"))
